// 将专业名归类，返回大类名
export function categorizeMajor(major) {
  if (!major) return '其他'
  for (const cat of Object.keys(CATEGORY_KEYWORDS)) {
    if (CATEGORY_KEYWORDS[cat].some(kw => major.includes(kw))) return cat
  }
  return '其他'
}
